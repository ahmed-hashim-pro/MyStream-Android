    // ── Lifecycle ─────────────────────────────────────────────────────────

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        setContentView(R.layout.activity_daily_hadith);

        // Nav bar
        getWindow().setNavigationBarColor(ContextCompat.getColor(this, R.color.background_main));

        // Navy hero header
        if (getSupportActionBar() != null) getSupportActionBar().hide();
        HeroController.attach(this).back().centered().title(R.string.hadith_title).apply();

        // Views
        tvHadithText = findViewById(R.id.tv_hadith_text);
        tvHadithSource = findViewById(R.id.tv_hadith_source);
        tvHadithNarrator = findViewById(R.id.tv_hadith_narrator);
        tvHadithCounter = findViewById(R.id.tv_hadith_counter);
        cardHadith = findViewById(R.id.card_hadith);

        ImageButton btnPrevious = findViewById(R.id.btn_previous);
        ImageButton btnNext = findViewById(R.id.btn_next);
        ImageButton btnShare = findViewById(R.id.btn_share);

        // Today's hadith
        int dayOfYear = Calendar.getInstance().get(Calendar.DAY_OF_YEAR);
        currentIndex = dayOfYear % HADITHS.length;

        displayHadith(currentIndex);

        // Navigation
        btnPrevious.setOnClickListener(v -> navigatePrevious());
        btnNext.setOnClickListener(v -> navigateNext());
        btnShare.setOnClickListener(v -> shareHadith());

        // Swipe gesture
        gestureDetector = new GestureDetector(this, new SwipeGestureListener());
        cardHadith.setOnTouchListener((v, event) -> {
            gestureDetector.onTouchEvent(event);
            return true;
        });
    }

    // ── Display ───────────────────────────────────────────────────────────

    private void displayHadith(int index) {
        String[] hadith = HADITHS[index];
        tvHadithText.setText(hadith[0]);
        tvHadithSource.setText(hadith[1]);
        tvHadithNarrator.setText(hadith[2]);
        tvHadithCounter.setText((index + 1) + " / " + HADITHS.length);
    }

    // ── Navigation ────────────────────────────────────────────────────────

    private void navigatePrevious() {
        currentIndex = (currentIndex - 1 + HADITHS.length) % HADITHS.length;
        displayHadith(currentIndex);
    }

    private void navigateNext() {
        currentIndex = (currentIndex + 1) % HADITHS.length;
        displayHadith(currentIndex);
    }

    // ── Share ─────────────────────────────────────────────────────────────

    private void shareHadith() {
        String[] hadith = HADITHS[currentIndex];
        String shareText = hadith[0] + "\n\n" + hadith[1] + "\n" + hadith[2];

        Intent shareIntent = new Intent(Intent.ACTION_SEND);
        shareIntent.setType("text/plain");
        shareIntent.putExtra(Intent.EXTRA_TEXT, shareText);
        startActivity(Intent.createChooser(shareIntent, getString(R.string.hadith_share_chooser)));
    }

    // ── Swipe gesture listener ────────────────────────────────────────────

    private class SwipeGestureListener extends GestureDetector.SimpleOnGestureListener {
        private static final int SWIPE_THRESHOLD = 100;
        private static final int SWIPE_VELOCITY_THRESHOLD = 100;

        @Override
        public boolean onDown(MotionEvent e) {
            return true;
        }

        @Override
        public boolean onFling(MotionEvent e1, MotionEvent e2, float velocityX, float velocityY) {
            if (e1 == null || e2 == null) return false;

            float diffX = e2.getX() - e1.getX();
            float diffY = e2.getY() - e1.getY();

            if (Math.abs(diffX) > Math.abs(diffY)
                    && Math.abs(diffX) > SWIPE_THRESHOLD
                    && Math.abs(velocityX) > SWIPE_VELOCITY_THRESHOLD) {
                if (diffX > 0) {
                    // Swipe right → previous (RTL-friendly: next in Arabic reading order)
                    navigateNext();
                } else {
                    // Swipe left → next (RTL-friendly: previous in Arabic reading order)
                    navigatePrevious();
                }
                return true;
            }
            return false;
        }
    }

    /**
     * Returns the total number of hadiths in the collection.
     * Can be used by other components (e.g. notification receiver).
     */
    public static int getHadithCount() {
        return HADITHS.length;
    }

    /**
     * Returns the hadith at the given index as a String array: {text, source, narrator}.
     */
    public static String[] getHadith(int index) {
        return HADITHS[index % HADITHS.length];
    }
